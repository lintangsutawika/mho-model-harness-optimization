"""Reward synthesis f: given a train sample x and a model spec sigma, produce x' = f(x, sigma).

x' is x with ONLY the reward changed: instruction.md + task.toml are copied byte-identical (the
problem is unchanged); tests/ is replaced with an EXECUTABLE REWARD RULE + a manifest.

The executable rule (tests/reward_rule.py) is GENERIC: it reads its config (expected answer and
the sigma-checks) from realization.json, and takes the artifact paths as arguments:
    python3 /tests/reward_rule.py /tests/../realization.json /workspace/output.txt /workspace/trajectory.json
It is runnable standalone (for verification) and is invoked by the thin tests/test.sh wrapper
(harbor's entrypoint). It evaluates each `checks` (boolean expressions over output + trajectory)
plus answer correctness, then writes /logs/verifier/reward.txt (float [0,1]) + sigma_info.json.

reward = max(0, min(1, 0.5 * answer_correctness + 0.5 * checks_passed_fraction))
harbor parses reward.txt via float() (verifier/verifier.py:_parse_reward_text).

Usage:
  python -m mho.data.reward_synthesis --task <x dir> --spec <model_spec.md> --out <x' dir>
"""
from __future__ import annotations

import argparse
import json
import os
import re
import shutil
import sys
from pathlib import Path

# Generic executable reward rule. @TOKENS@ are substituted by _render_rule (plain string replace).
# Reads config (expected answer + checks) from realization.json; takes artifact paths as argv, so
# it is reusable across any harbor task that provides the manifest + artifacts.
RULE_TEMPLATE = r'''#!/usr/bin/env python3
"""Generic executable reward rule generated by mho.data.reward_synthesis.

Usage: reward_rule.py <realization.json> <output_path> <trajectory_path>
Reads the expected answer + sigma-checks from realization.json, scores answer correctness and the
checks over the output/trajectory, and writes /logs/verifier/reward.txt (float [0,1]).
"""
import json
import re
import sys
from pathlib import Path

ANSWER_RE = re.compile(r"(?:^|\n)\s*Answer:\s*(.+?)\s*$\s*", re.MULTILINE)


def _read(path: str) -> str:
    try:
        return Path(path).read_text(encoding="utf-8", errors="replace")
    except Exception:
        return ""


def _load_config(manifest: str) -> tuple[str, str, list]:
    data = json.loads(_read(manifest) or "{}")
    expected = str(data.get("expected_answer", ""))
    checks = list(data.get("checks", []))
    sigma = str(data.get("sigma", ""))
    return sigma, expected, checks


def _extract_answer(text: str) -> str:
    matches = ANSWER_RE.findall(text)
    return matches[-1].lstrip("$").strip() if matches else ""


def _norm(text: str) -> str:
    return " ".join(str(text).strip().lower().split())


def _correctness(cand: str, exp: str) -> float:
    if not cand or not exp:
        return 0.0
    try:
        from math_verify import parse, verify
        if verify(parse(exp), parse(cand)):
            return 1.0
    except Exception:
        pass
    try:
        import sympy as sp
        from sympy.parsing.latex import parse_latex
        if sp.simplify(parse_latex(exp) - parse_latex(cand)) == 0:
            return 1.0
    except Exception:
        pass
    return float(_norm(cand) == _norm(exp))


def run(manifest: str, output_path: str, traj_path: str) -> int:
    sigma, expected, checks = _load_config(manifest)
    output = _read(output_path)
    traj = _read(traj_path)
    cand = _extract_answer(output)
    corr = _correctness(cand, expected)
    results = []
    for i, expr in enumerate(checks):
        try:
            ok = bool(eval(expr, {"__builtins__": {}}, {"output": output, "traj": traj}))  # noqa: S307
        except Exception as e:
            ok = False
            expr = f"{expr}  # ERROR: {e}"
        results.append({"i": i, "check": expr, "passed": ok})
    frac = (sum(1 for c in results if c["passed"]) / len(results)) if results else 0.0
    reward = max(0.0, min(1.0, 0.5 * corr + 0.5 * frac))
    info = {"sigma": sigma, "correct": corr, "checks_passed": frac, "checks": results, "reward": reward}
    out_dir = Path("/logs/verifier")
    out_dir.mkdir(parents=True, exist_ok=True)
    (out_dir / "reward.txt").write_text(f"{reward:.4f}\n")
    (out_dir / "sigma_info.json").write_text(json.dumps(info, indent=2))
    print(json.dumps(info, indent=2))
    return 0 if reward >= 0.5 else 1


if __name__ == "__main__":
    if len(sys.argv) < 4:
        print("usage: reward_rule.py <realization.json> <output_path> <trajectory_path>", file=sys.stderr)
        raise SystemExit(2)
    raise SystemExit(run(sys.argv[1], sys.argv[2], sys.argv[3]))
'''


def _extract_expected_answer(task: Path) -> str:
    """Grab the expected answer from x: task.toml [metadata] answer, else test.py EXPECTED_ANSWER."""
    toml = task / "task.toml"
    if toml.exists():
        m = re.search(r"answer\s*=\s*[\"']?([^\"'\\n]+)", toml.read_text())
        if m:
            return m.group(1).strip()
    testpy = task / "tests" / "test.py"
    if testpy.exists():
        m = re.search(r"EXPECTED_ANSWER\s*=\s*[\"']([^\"']*)", testpy.read_text())
        if m:
            return m.group(1)
    return ""


def _render_rule() -> str:
    """The rule is generic - no per-spec tokens to inject; it reads config from realization.json."""
    return RULE_TEMPLATE


def realize(task: Path, spec, out: Path) -> Path:
    """f(x, sigma) -> x'.

    x' is x with ONLY the reward changed: instruction.md/task.toml copied byte-identical; tests/
    replaced by a generic executable reward rule (reward_rule.py) + realization.json (its config)
    + a thin test.sh wrapper.
    """
    out.mkdir(parents=True, exist_ok=True)
    # No dataset copy: instruction.md + task.toml are HARDLINKED from the base task (share the
    # inode / storage, resolve normally in a mount), so only tests/ + realization.json are new.
    for name in ("instruction.md", "task.toml"):
        src = task / name
        if src.exists():
            dst = out / name
            try:
                os.link(src, dst)          # hardlink: no content duplication
            except OSError:
                shutil.copy2(src, dst)     # fallback if hardlink unsupported (e.g. cross-device)
    tests = out / "tests"
    tests.mkdir(parents=True, exist_ok=True)
    (tests / "reward_rule.py").write_text(_render_rule(), encoding="utf-8")
    # realization.json = the rule's config (also human provenance). Test.sh passes it to the rule.
    expected = _extract_expected_answer(task)
    manifest = {"sigma": spec.name, "from_task": str(task),
               "expected_answer": expected, "checks": spec.checks}
    (out / "realization.json").write_text(json.dumps(manifest, indent=2), encoding="utf-8")
    # test.sh = thin harbor entrypoint: pass realization.json + the artifact paths to the rule.
    # Manifest defaults to the task-root realization.json (one level above /tests); artifact paths
    # overridable via env so any harbor task can point at its own artifacts.
    (tests / "test.sh").write_text(
        r"""#!/bin/bash
set -Eeuo pipefail
echo '=== sigma reward rule ==='
mkdir -p /logs/verifier
MANIFEST="${REALIZATION_MANIFEST:-/tests/../realization.json}"
OUT="${OUTPUT_ARTIFACT:-/workspace/output.txt}"
TRAJ="${TRAJ_ARTIFACT:-/workspace/trajectory.json}"
exec python3 /tests/reward_rule.py "$MANIFEST" "$OUT" "$TRAJ"
""",
        encoding="utf-8",
    )
    return out


def main(argv: list[str] | None = None) -> int:
    from mho.optimizer import model_spec
    p = argparse.ArgumentParser(description=__doc__.splitlines()[0])
    p.add_argument("--task", required=True, type=Path, help="source task dir x (instruction.md + task.toml)")
    p.add_argument("--spec", required=True, type=Path, help="model spec (model_specs/<name>.md)")
    p.add_argument("--out", required=True, type=Path, help="output x' task dir")
    args = p.parse_args(argv)
    spec, _body = model_spec.parse_spec(args.spec)  # validate + load
    out = realize(args.task, spec, args.out)
    print(f"[reward_synthesis] x' = f(x, sigma={spec.name}, {len(spec.checks)} checks) -> {out}\n"
          f"  generic rule: {out}/tests/reward_rule.py (reads config from {out}/realization.json)")
    return 0


if __name__ == "__main__":
    raise SystemExit(main())